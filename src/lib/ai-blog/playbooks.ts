/** 유형과 역할에 맞는 소제목 */
export function sectionHeading(
  type: AiBlogArticleType,
  section: PlaybookSection,
  c: PlaybookContext,
): string {
  if (type === "expert") return section.heading(c);
  return ROLE_HEADING_BY_TYPE[type][section.role](c);
}

export function playbookOf(category: AiBlogCategory): CategoryPlaybook {
  return CATEGORY_PLAYBOOKS[category] ?? etc;
}

/** 해당 업종을 제외한 다른 업종의 대표 어휘 — 타 분야 혼입 판정에 쓴다 */
export function otherDomainTerms(category: AiBlogCategory): string[] {
  const own = new Set(playbookOf(category).vocabulary);
  return Object.values(CATEGORY_PLAYBOOKS)
    .filter((p) => p.id !== category)
    .flatMap((p) => p.signature)
    .filter((term) => !own.has(term));
}
